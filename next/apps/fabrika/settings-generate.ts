// Writes the shipped settings schemas and the generated reference from the declarations, through
// the same library functions the freshness test reads. The reference's section sits between two
// markers in docs/settings-reference.md, so the words around it stay as the docs step wrote them.
import { NodeRuntime, NodeServices } from "@effect/platform-node";
import * as Declarations from "@kampus/libfabrika/settings/Declarations";
import * as Files from "@kampus/libfabrika/settings/Files";
import * as JsonSchema from "@kampus/libfabrika/settings/JsonSchema";
import * as Reference from "@kampus/libfabrika/settings/Reference";
import { Effect, FileSystem, Path } from "effect";

const BEGIN = "<!-- generated by settings-generate.ts: begin -->";
const END = "<!-- generated by settings-generate.ts: end -->";

NodeRuntime.runMain(
  Effect.gen(function* () {
    const fs = yield* FileSystem.FileSystem,
      path = yield* Path.Path;

    for (const file of ["person", "repo"] as const) {
      const document = JsonSchema.make(Files.schema(Declarations.all, file));
      yield* fs.writeFileString(path.join(import.meta.dirname, `${file}.json`), JsonSchema.format(document));
    }

    const reference = path.resolve(import.meta.dirname, "../../../docs/settings-reference.md");
    const text = (yield* fs.exists(reference)) ? yield* fs.readFileString(reference) : `${BEGIN}\n${END}\n`;
    const [before = "", rest = ""] = text.split(BEGIN);
    const after = rest.split(END)[1] ?? "\n";
    yield* fs.writeFileString(reference, `${before}${BEGIN}\n${Reference.markdown(Declarations.all)}${END}${after}`);
  }).pipe(Effect.provide(NodeServices.layer)),
);
